# 本质上是在向终端输出一串 ANSI/VT 转义序列:
# - \x1b[3J: 清除终端的滚动缓冲区/历史行;
# - \x1b[2J: 清除当前可见屏幕;
# - \x1b[H: 把光标移动到左上角;
# - end="": 让 print 不要追加换行,否则光标会从左上角又跑到下一行;
#
# 其中:
# - `ESC`：转义开始;
# - `[`：进入 CSI 控制序列;
# - `3`,`2`：参数字节;
# - `J`,`H`：最终字节,决定具体功能;
#
# `end=""`: 作用是避免输出换行
# `flush=True`: 转义序列立即刷新
print("\x1b[3J\x1b[2J\x1b[H", end="", flush=True)
